#!/usr/bin/env node
// Builds the team map and each template's team section from the template.json files.
// Created by @meta_alchemist (https://x.com/meta_alchemist).
// Writes: docs/TEAM-MAP.md; the "Team inputs and outputs" block in each getting-started SKILL.md and HOW-TO-USE.md;
//         the TEAM memory fact in each recipe.json. Run `node scripts/build-recipe.mjs <dir>` afterwards for shipping
//         templates (npm run team does both). With --check it writes nothing and exits 1 if anything is out of date.
// Usage: node scripts/build-team.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadTeam, OWNER_ARTIFACTS, ARTIFACT_DIR, MEMORY_DIR, TEAM_SPEC } from "./lib/team.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const BEGIN = "<!-- team:begin (generated by scripts/build-team.mjs from template.json; edit template.json, not this block) -->";
const END = "<!-- team:end -->";
export const TEAM_FACT_PREFIX = "TEAM:";
const CREDIT = "Created by @meta_alchemist (https://x.com/meta_alchemist).";

const team = loadTeam(ROOT);
const bySlug = new Map(team.map((t) => [t.slug, t]));
const short = (t) => `${t.slug.slice(0, 2)} ${t.shortName || t.name}`;
const producersOf = (artifact, except) => team.filter((t) => t !== except && (t.produces || []).some((p) => p.artifact === artifact));
const consumersOf = (artifact, except) => team.filter((t) => t !== except && (t.consumes || []).some((c) => c.artifact === artifact));
const fromText = (artifact, self) => {
  if (OWNER_ARTIFACTS.includes(artifact) && !producersOf(artifact, self).length) return "the owner";
  const names = producersOf(artifact, self).map(short);
  const owner = OWNER_ARTIFACTS.includes(artifact) ? ["the owner"] : [];
  return [...owner, ...names].join(", ") || "no template in this kit yet";
};
const WHERE = {
  "evidence-pack": "the pack path the owner gives, or `" + ARTIFACT_DIR + "/evidence-pack/`",
  "game-profile": "`pack.profile` in the evidence pack, or `" + ARTIFACT_DIR + "/game-profile/`",
};
const OWNER_MISSING = {
  "evidence-pack": "Stop and ask the owner for a pack. Without one there is no grade; record NOT_RUN.",
  "game-profile": "Ask the getting-started questions and write it with the owner. A missing threshold leaves its line unmeasured, never a default.",
};
const defaultMissing = (use, self) => OWNER_MISSING[use.artifact] ?? (use.required
  ? "Stop and ask the owner for it. Do not grade or draft without it."
  : `Continue without it. Start the report with "ASSUMPTION: no ${use.artifact} available" and say which checks it would have informed. Leave lines that need it unmeasured. Never invent the missing data.`);

function block(t) {
  const lines = [BEGIN, "", "## Team inputs and outputs", ""];
  lines.push(`This template works on its own. When other templates from the kit run in the same game project, they exchange files under \`${ARTIFACT_DIR}/<artifact>/\` (read the newest file) and share an append-only memory under \`${MEMORY_DIR}/\`. Team spec ${t.teamSpec ?? TEAM_SPEC}.`, "");
  const uses = t.consumes || [];
  if (uses.length) {
    lines.push("Before acting, look for these inputs:", "", "| Input | From | Where to look | If it is missing |", "|---|---|---|---|");
    for (const u of uses) lines.push(`| \`${u.artifact}\` (${u.required ? "required" : "optional"}, ${t.compat?.consumes?.[u.artifact] ?? "any version"}) | ${fromText(u.artifact, t)} | ${WHERE[u.artifact] ?? `\`${ARTIFACT_DIR}/${u.artifact}/\``} | ${u.whenMissing || defaultMissing(u, t)} |`);
    lines.push("");
  }
  const outs = t.produces || [];
  if (outs.length) {
    lines.push("After acting, save these outputs as local files for the human to review:", "", "| Output | Format | Where | Read by |", "|---|---|---|---|");
    for (const o of outs) {
      const readers = consumersOf(o.artifact, t).map(short).join(", ") || "the owner";
      lines.push(`| \`${o.artifact}\` ${o.version} | ${o.format} | \`${ARTIFACT_DIR}/${o.artifact}/\` | ${readers} |`);
    }
    lines.push("", `Each output file is JSON with \`artifact\`, \`version\`, \`producer\` (this template's id and version), \`createdAt\` (UTC), \`synthetic\` and \`items\`, as the kit's \`spec/artifacts/<artifact>.schema.json\` describes. Name files \`<UTC date>-<short label>.json\` so the newest sorts last.`, "");
  }
  const m = t.memory || { reads: [], writes: [] };
  lines.push("Shared memory:", "");
  lines.push(`- Before acting, read ${m.reads.length ? m.reads.map((x) => `\`${x}\``).join(", ") : "no topics"} from \`${MEMORY_DIR}/<topic>.jsonl\`. Skip records that have expired or that a later record supersedes.`);
  lines.push(`- Write only ${m.writes.length ? m.writes.map((x) => `\`${x}\``).join(", ") : "nothing"}. Append one line per record with \`engine/team-memory.mjs\` (or the same JSON by hand): id, UTC time, writer (\`${t.id}\` and \`${t.version}\`), topic, kind, summary, data, source, confidence (measured, reported or assumed), expires_at and supersedes. Never edit or delete a line; supersede it.`);
  lines.push("- Never put secrets, names, handles, wallets, emails or raw user ids in memory. Refer to a person or account only by `node engine/team-memory.mjs hash <id>`, which needs the salt in `GROKBOT_TEAM_SALT`. Run `node engine/team-memory.mjs lint` before you finish.");
  lines.push("- Keep `.grokbot-team/` out of a public game repository (add it to `.gitignore`); in a private one, commit it so the append-only rule can be checked against history.");
  lines.push("", END);
  return lines.join("\n");
}

function teamFact(t) {
  const m = t.memory || { reads: [], writes: [] };
  const ins = (t.consumes || []).map((u) => `${u.artifact}${u.required ? " (required)" : ""}`).join(", ") || "none";
  const outs = (t.produces || []).map((o) => o.artifact).join(", ") || "none";
  return `${TEAM_FACT_PREFIX} this is ${t.id} version ${t.version}, team spec ${t.teamSpec}. Before acting, read inputs from ${ARTIFACT_DIR}/<artifact>/ (${ins}) and memory topics ${m.reads.join(", ") || "none"} from ${MEMORY_DIR}/. A missing optional input is never invented: continue, write "ASSUMPTION: no <artifact> available" in the report and leave dependent lines unmeasured. Save outputs (${outs}) as local files for human review. Write memory only to ${m.writes.join(", ") || "no topics"}, with no personal data or secrets; hash subject ids with GROKBOT_TEAM_SALT.`;
}

function upsertBlock(text, b, anchor) {
  const re = new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`);
  if (re.test(text)) return text.replace(re, () => b);
  if (anchor && text.includes(anchor)) return text.replace(anchor, () => `${b}\n\n${anchor}`);
  return text.trimEnd() + "\n\n" + b + "\n";
}

const stale = [];
const write = (file, next) => {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (prev === next) return;
  stale.push(path.relative(ROOT, file));
  if (!CHECK) fs.writeFileSync(file, next);
};

for (const t of team) {
  if (!t.produces && !t.consumes) continue;
  const b = block(t);
  const gs = path.join(t.dir, "skills", t.gettingStarted, "SKILL.md");
  if (fs.existsSync(gs)) write(gs, upsertBlock(fs.readFileSync(gs, "utf8"), b));
  const how = path.join(t.dir, "HOW-TO-USE.md");
  if (fs.existsSync(how)) write(how, upsertBlock(fs.readFileSync(how, "utf8"), b.replace("## Team inputs and outputs", "## Works with other templates"), "## Safety defaults"));
  const rp = path.join(t.dir, "recipe.json");
  const sources = fs.existsSync(path.join(t.dir, "memory.json")) ? path.join(t.dir, "memory.json") : rp;
  const raw = fs.readFileSync(sources, "utf8"), json = JSON.parse(raw);
  const indent = /^[\[{]\n( +)/.exec(raw)?.[1].length ?? 2; // keep the file's own indentation
  const mem = Array.isArray(json) ? json : json.memory;
  if (Array.isArray(mem)) {
    const fact = { kind: "profile", content: teamFact(t) };
    const i = mem.findIndex((x) => String(x.content).startsWith(TEAM_FACT_PREFIX));
    if (i >= 0) mem[i] = fact; else mem.push(fact);
    write(sources, JSON.stringify(json, null, indent) + "\n");
  }
}

// ---------- docs/TEAM-MAP.md ----------
const shipping = team.filter((t) => t.slug !== "00-starter-template");
const universal = new Set(["grade-record", "ticket-draft"]);
const node = (t) => `T${t.slug.slice(0, 2)}`;
const mm = ["```mermaid", "flowchart LR"];
mm.push('  OWNER(["Owner: game profile, evidence packs, tracker export, change list"])');
mm.push('  ALL["Every template: grade records and ticket drafts"]');
for (const t of shipping) mm.push(`  ${node(t)}["${short(t)}${t.status === "preview" ? " (preview)" : ""}"]`);
const edges = new Set();
for (const P of shipping) for (const o of P.produces || []) {
  if (universal.has(o.artifact)) continue;
  for (const C of consumersOf(o.artifact, P)) if (C.slug !== "00-starter-template") edges.add(`  ${node(P)} -- ${o.artifact} --> ${node(C)}`);
}
for (const a of universal) for (const C of consumersOf(a)) if (C.slug !== "00-starter-template") edges.add(`  ALL -- ${a} --> ${node(C)}`);
for (const a of OWNER_ARTIFACTS.filter((x) => !["game-profile", "evidence-pack"].includes(x))) for (const C of consumersOf(a)) if (C.slug !== "00-starter-template") edges.add(`  OWNER -- ${a} --> ${node(C)}`);
mm.push(...[...edges].sort(), "```");

const rows = [];
const artifacts = [...new Set(team.flatMap((t) => [...(t.produces || []), ...(t.consumes || [])].map((x) => x.artifact)))].sort();
for (const a of artifacts) {
  const prods = producersOf(a);
  const fmt = prods.find(Boolean)?.produces.find((x) => x.artifact === a)?.format ?? "JSON";
  const by = [...(OWNER_ARTIFACTS.includes(a) ? ["Owner"] : []), ...(universal.has(a) && prods.length > 3 ? ["Every template"] : prods.map(short))].join(", ") || "none yet";
  const cons = consumersOf(a);
  const to = cons.length === team.length || (cons.length > 3 && OWNER_ARTIFACTS.includes(a) && ["game-profile", "evidence-pack"].includes(a)) ? "Every template" : cons.map(short).join(", ") || "the owner";
  rows.push(`| ${by} | [\`${a}\`](../spec/artifacts/${a}.schema.json) | ${to} | ${fmt} |`);
}

const mem = ["| Topic | Written by | Read by |", "|---|---|---|"];
for (const topic of ["decisions", "incidents", "entitlements", "balance", "regions", "releases"]) {
  const w = team.filter((t) => t.memory?.writes?.includes(topic));
  const r = team.filter((t) => t.memory?.reads?.includes(topic));
  const list = (xs) => (xs.length === team.length ? "Every template" : xs.map(short).join(", ") || "none yet");
  mem.push(`| \`${topic}\` | ${list(w)} | ${list(r)} |`);
}

const map = `# Team map

${CREDIT} Generated by \`npm run team\` from every \`template.json\`; do not edit by hand.

Every template works alone. Run two or more in the same game project and they hand work to each other through files, so nobody retypes findings. This page shows who makes what and who reads it. The contract for each file is in [spec/artifacts/](../spec/artifacts/), the shared memory record is [spec/shared-memory.schema.json](../spec/shared-memory.schema.json), and version rules are in [VERSIONING.md](VERSIONING.md). Team spec ${TEAM_SPEC}.

## How the files flow

Every template also reads the owner's \`game-profile\` and \`evidence-pack\`; those arrows are left out to keep the picture readable.

${mm.join("\n")}

## Who makes what

| Producer | Artifact | Consumer | File format |
|---|---|---|---|
${rows.join("\n")}

## Where the files live in your game project

\`\`\`
your-game/
  .grokbot-team/
    artifacts/<artifact>/<UTC date>-<label>.json   one folder per artifact, newest sorts last
    memory/<topic>.jsonl                            append-only shared memory, one file per topic
\`\`\`

A consumer reads the newest file in the folder. When a folder is empty or missing, an optional input is skipped with a clearly marked assumption ("ASSUMPTION: no feel-findings available") and the lines that needed it stay unmeasured. A required input (the owner's game profile and evidence pack) stops the run and the bot asks the owner. No template ever invents the missing data. Check a file against its contract with \`node scripts/check-artifact.mjs <file or folder>\`.

## Shared memory topics

Templates read the topics they need before acting and append only to the topics they own. See [SHARED-MEMORY.md](SHARED-MEMORY.md).

${mem.join("\n")}

## Check compatibility

\`npm run compat\` reports OK, WARN or BREAK for every pair of templates in the table above, with the reason and the fix.
`;
write(path.join(ROOT, "docs", "TEAM-MAP.md"), map);

if (CHECK) {
  for (const f of stale) console.log(`STALE ${f}`);
  console.log(`build-team --check: ${stale.length} stale file(s) -> ${stale.length ? "FAIL" : "OK"}`);
  process.exit(stale.length ? 1 : 0);
}
console.log(`build-team: ${team.length} templates, ${stale.length} file(s) written`);
