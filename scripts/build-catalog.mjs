#!/usr/bin/env node
// Regenerates TEMPLATES.md from every templates/*/template.json and HOW-TO-USE.md When line.
// Created by @meta_alchemist (https://x.com/meta_alchemist).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { whenToUse } from "./lib/when-to-use.mjs";
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const T = path.join(ROOT, "templates");
const rows = fs.readdirSync(T).sort().filter((d) => fs.existsSync(path.join(T, d, "template.json")))
  .map((d) => JSON.parse(fs.readFileSync(path.join(T, d, "template.json"), "utf8")));
const link = (m) => m.install.shareLinkStatus === "live" && m.install.grokBotShareLink?.startsWith("grokbot://")
  ? `[Add to Grok Bot](${m.install.grokBotShareLink})`
  : "Share link coming soon";
const guide = (m) => fs.existsSync(path.join(ROOT, "guides", "game-design-pipelines", `${m.slug}.md`)) ? `, [pipeline](guides/game-design-pipelines/${m.slug}.md)` : "";
const when = (m) => {
  const howto = fs.readFileSync(path.join(T, m.slug, "HOW-TO-USE.md"), "utf8");
  return whenToUse(m.slug, howto).replaceAll("|", "/");
};
const row = (m) => `| ${m.slug.slice(0, 2)} | [${m.shortName || m.name}](templates/${m.slug}/) | ${m.name} | ${m.version ?? ""} | ${when(m)} | ${m.summary} | [start here](templates/${m.slug}/README.md#start-here), [how to use](templates/${m.slug}/HOW-TO-USE.md), [prompts](templates/${m.slug}/PROMPTS.md)${guide(m)} | ${link(m)} |`;
const head = ["| # | Short name | Full name | Version | When to use | What it does | Read this | Share link |", "|---|---|---|---|---|---|---|---|"];
const shipping = rows.filter((m) => (m.status ?? "shipping") === "shipping");
const preview = rows.filter((m) => m.status === "preview");
const L = ["# Template catalog", "", "Created by @meta_alchemist (https://x.com/meta_alchemist). Generated by `npm run catalog` from each `template.json` and `HOW-TO-USE.md`. Do not edit by hand.", "",
  "New here? Do not pick from this table yet. Start with the five bots in [Get started with your AI gaming team](GETTING-STARTED.md).", "",
  "Every share link is still **Share link coming soon**, so there is nothing to open yet. Use the manual steps in [INSTALL.md](INSTALL.md) (Option B), import `recipe.json` if you see that action, or use the files with another AI (Option C). When a link is live, the Share link column becomes a real link. How the bots hand work to each other is in the [team map](docs/TEAM-MAP.md). The short name is what the rest of the kit calls the bot. The full name is the title on its folder.", "",
  `## Shipping templates (${shipping.length})`, "", ...head, ...shipping.map(row)];
if (preview.length) {
  L.push("", `## Preview templates (${preview.length}, not shipping)`, "",
    "These work and their tests pass, but they are not yet held to the release standard. Each one's README lists what it needs before it can ship. Use them to try an idea, not to grade a release.", "",
    ...head, ...preview.map(row));
}
L.push("", "## Not included yet", "", "Template numbers 04, 07, 08, and 16 are not in this release, and neither are Studio Director or Game Clipmaker. See [READINESS.md](READINESS.md) and [CHANGELOG.md](CHANGELOG.md) for why. Numbers that are here stay stable.", "");
fs.writeFileSync(path.join(ROOT, "TEMPLATES.md"), L.join("\n"));
console.log(`TEMPLATES.md: ${shipping.length} shipping, ${preview.length} preview`);
