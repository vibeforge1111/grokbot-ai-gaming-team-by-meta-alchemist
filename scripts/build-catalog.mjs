#!/usr/bin/env node
// Regenerates TEMPLATES.md from every templates/*/template.json. Created by @meta_alchemist (https://x.com/meta_alchemist).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const T = path.join(ROOT, "templates");
const rows = fs.readdirSync(T).sort().filter((d) => fs.existsSync(path.join(T, d, "template.json")))
  .map((d) => JSON.parse(fs.readFileSync(path.join(T, d, "template.json"), "utf8")));
const link = (m) => m.install.shareLinkStatus === "live" && m.install.grokBotShareLink?.startsWith("grokbot://")
  ? `[Add to Grok Bot](${m.install.grokBotShareLink})`
  : "pending review";
const guide = (m) => fs.existsSync(path.join(ROOT, "guides", "game-design-pipelines", `${m.slug}.md`)) ? `, [pipeline](guides/game-design-pipelines/${m.slug}.md)` : "";
const row = (m) => `| ${m.slug.slice(0, 2)} | [${m.name}](templates/${m.slug}/) | ${m.version ?? ""} | ${m.stage} | ${m.summary} | ${link(m)} | [how to use](templates/${m.slug}/HOW-TO-USE.md), [prompts](templates/${m.slug}/PROMPTS.md)${guide(m)} |`;
const head = ["| # | Template | Version | Stage | What it does | Add to Grok Bot | Guide |", "|---|---|---|---|---|---|---|"];
const shipping = rows.filter((m) => (m.status ?? "shipping") === "shipping");
const preview = rows.filter((m) => m.status === "preview");
const L = ["# Template catalog", "", "Created by @meta_alchemist (https://x.com/meta_alchemist). Generated by `npm run catalog` from each `template.json`; do not edit by hand.", "",
  "Install paths are in [INSTALL.md](INSTALL.md). Share links are created after each template is reviewed; until then the slot reads **pending review** and you can use the manual setup (Option B) or other agents (Option C). How the templates hand work to each other is in the [team map](docs/TEAM-MAP.md).", "",
  `## Shipping templates (${shipping.length})`, "", ...head, ...shipping.map(row)];
if (preview.length) {
  L.push("", `## Preview templates (${preview.length}, not shipping)`, "",
    "These work and their tests pass, but they are not yet held to the release standard. Each one's README lists what it needs before it can ship. Use them to try an idea, not to grade a release.", "",
    ...head, ...preview.map(row));
}
L.push("", "## Not included yet", "", "See [CHANGELOG.md](CHANGELOG.md) for templates held back from this release and why.", "");
fs.writeFileSync(path.join(ROOT, "TEMPLATES.md"), L.join("\n"));
console.log(`TEMPLATES.md: ${shipping.length} shipping, ${preview.length} preview`);
